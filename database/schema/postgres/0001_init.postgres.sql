-- PostgreSQL schema for the uptime worker.
--
-- This is the single-shot schema for `DATABASE_TYPE=postgres`. SQLite has to
-- grow through 11 files (migrations/0001..0011) because it cannot ALTER ... ADD
-- COLUMN IF NOT EXISTS or rebuild a CHECK constraint; PG can express the same
-- end-state directly, so the PG schema is delivered as one idempotent file
-- rather than a parallel 11-file chain.
--
-- Where the D1 schema encodes a value as `INTEGER 0/1`, this schema does the
-- same. The codebase reads and normalises columns such as `active` and
-- `check_ssl` as numbers; switching them to PG BOOLEAN would have to be a
-- code change, not just a schema change, and belongs to a later phase.
--
-- `WITHOUT ROWID` does not exist on PG; tables here are heap tables by
-- default, which is the same layout in practice.
--
-- All `CREATE ... IF NOT EXISTS` here means this file is re-runnable. The
-- migration runner's schema_migrations ledger prevents a redundant re-apply,
-- so `IF NOT EXISTS` is purely defensive: it keeps a second apply a no-op if
-- for some reason the ledger was lost, and it never produces a partial
-- rebuild the way SQLite's "no ADD COLUMN IF NOT EXISTS" did.
--
-- Uptime Worker 的 PostgreSQL 模式：DATABASE_TYPE=postgres 使用单次初始化的模式。
-- SQLite 不能 ADD COLUMN IF NOT EXISTS 或原地重建 CHECK，因此需经过 0001–0011
-- 共 11 个迁移；PG 可直接表达相同最终状态，故提供一个幂等文件而非平行迁移链。
-- D1 用 INTEGER 0/1 编码的值在此仍用整数，代码按数字读取并规范化；改为 PG
-- BOOLEAN 需要改代码而非仅改模式，属于后续阶段。PG 无 WITHOUT ROWID；此处默认
-- 堆表在实践中具有相同布局。所有 CREATE 使用 IF NOT EXISTS，因此可重跑；
-- schema_migrations 账本通常阻止重复执行，此保护仅在账本丢失等情况下使重跑无操作，
-- 不会产生 SQLite 缺少 ADD COLUMN IF NOT EXISTS 所带来的部分重建。

-- ---------------------------------------------------------------------------
-- Monitors. `num_id` starts as NULL on SQLite (backfilled from rowid); on PG
-- it is a real IDENTITY column so it has stable values from the moment the
-- row lands, without a backfill step. `agent_token` is NULL for every
-- transport monitor and set only for `type='agent'`. Both tokens get partial
-- indexes filtered on NOT NULL, so the admin lookup stays O(log n) against
-- only the rows that actually carry a token.
--
-- 监控项：SQLite 的 num_id 初始为 NULL 并由 rowid 回填；PG 使用 IDENTITY，
-- 行创建时即有稳定值，无需回填。agent_token 对传输类监控均为 NULL，仅 agent 类型
-- 设置；两个令牌均使用 NOT NULL 部分索引，只索引实际有令牌的行，使管理端查找
-- 保持 O(log n)。
CREATE TABLE IF NOT EXISTS monitors (
  id              TEXT PRIMARY KEY,
  num_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name            TEXT    NOT NULL,
  type            TEXT    NOT NULL CHECK (type IN ('http', 'tcp', 'dns', 'push', 'agent')),
  target          TEXT    NOT NULL,
  method          TEXT    NOT NULL DEFAULT 'GET',
  expected_status TEXT    NOT NULL DEFAULT '200-299',
  keyword         TEXT,
  interval_sec    INTEGER NOT NULL DEFAULT 60,
  timeout_ms      INTEGER NOT NULL DEFAULT 10000,
  warn_days       INTEGER NOT NULL DEFAULT 14,
  check_ssl       INTEGER NOT NULL DEFAULT 0,
  check_domain    INTEGER NOT NULL DEFAULT 0,
  check_dns       INTEGER NOT NULL DEFAULT 0,
  options_json    TEXT    NOT NULL DEFAULT '{}',
  push_token      TEXT,
  agent_token     TEXT,
  group_id        TEXT,
  active          INTEGER NOT NULL DEFAULT 1,
  created_at      INTEGER NOT NULL,
  updated_at      INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_monitors_push_token  ON monitors(push_token)  WHERE push_token  IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_monitors_agent_token ON monitors(agent_token) WHERE agent_token IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_monitors_group       ON monitors(group_id);

-- ---------------------------------------------------------------------------
-- Live state. One JSON blob for the whole dashboard, written once per tick.
-- 实时状态：整个仪表板共用一个 JSON 数据块，每次 tick 写入一次。
CREATE TABLE IF NOT EXISTS live_state (
  id         TEXT PRIMARY KEY,
  json       TEXT    NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Daily uptime rollup per monitor.
-- 每个监控项的每日可用率汇总。
CREATE TABLE IF NOT EXISTS monitor_uptime (
  monitor_id TEXT PRIMARY KEY,
  days_json  TEXT    NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Heartbeat ring buffer per monitor.
-- 每个监控项的心跳环形缓冲区。
CREATE TABLE IF NOT EXISTS heartbeat_ring (
  id         TEXT PRIMARY KEY,
  json       TEXT    NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Last received push heartbeat per push monitor.
-- 每个 Push 监控项最近收到的心跳。
CREATE TABLE IF NOT EXISTS push_heartbeats (
  monitor_id TEXT PRIMARY KEY,
  ts         INTEGER NOT NULL,
  status     INTEGER NOT NULL,
  msg        TEXT    NOT NULL DEFAULT '',
  ping       INTEGER NOT NULL DEFAULT 0
);

-- State transitions. SQLite's AUTOINCREMENT becomes BIGSERIAL.
-- 状态变化：SQLite 的 AUTOINCREMENT 在 PostgreSQL 中使用 BIGSERIAL。
CREATE TABLE IF NOT EXISTS events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_id TEXT    NOT NULL,
  status     INTEGER NOT NULL,
  message    TEXT,
  created_at INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_events_monitor ON events(monitor_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Accounts.
-- 账户。
CREATE TABLE IF NOT EXISTS users (
  id                   TEXT PRIMARY KEY,
  username             TEXT    NOT NULL,
  password_hash        TEXT    NOT NULL,
  created_at           INTEGER NOT NULL,
  updated_at           INTEGER NOT NULL,
  failed_count         INTEGER NOT NULL DEFAULT 0,
  locked_until         INTEGER NOT NULL DEFAULT 0
);

-- SQLite used `COLLATE NOCASE`; the PG equivalent is a functional unique
-- index over LOWER(), which the authSQL[db.type].findUserByName matches
-- (`LOWER(username) = LOWER($1)`).
--
-- SQLite 使用 COLLATE NOCASE；PG 对应方案是 LOWER() 函数唯一索引，
-- 与 authSQL[db.type].findUserByName 的 LOWER(username) = LOWER($1) 一致。
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users(LOWER(username));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    TEXT    NOT NULL,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL,
  user_agent TEXT
);

CREATE INDEX IF NOT EXISTS idx_sessions_user    ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);

-- ---------------------------------------------------------------------------
-- Notifications.
-- 通知。
CREATE TABLE IF NOT EXISTS notifications (
  id          TEXT PRIMARY KEY,
  name        TEXT    NOT NULL,
  type        TEXT    NOT NULL CHECK (type IN (
              'telegram','feishu','slack','discord','webhook','apprise','serverchan'
            )),
  config_json TEXT    NOT NULL,
  active      INTEGER NOT NULL DEFAULT 1,
  created_at  INTEGER NOT NULL,
  updated_at  INTEGER NOT NULL
);

-- PostgreSQL IDENTITY matches the D1 `SELECT rowid AS num_id` numeric key.
--
-- PostgreSQL 的 IDENTITY 与 D1 的 `SELECT rowid AS num_id` 数字键一致。
CREATE TABLE IF NOT EXISTS monitor_groups (
  id         TEXT PRIMARY KEY,
  num_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name       TEXT    NOT NULL,
  weight     INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_monitor_groups_name ON monitor_groups(name);

-- Tag vocabulary.
-- 标签词表。
CREATE TABLE IF NOT EXISTS tags (
  id         TEXT PRIMARY KEY,
  name       TEXT    NOT NULL,
  color      TEXT    NOT NULL DEFAULT '#006FEE',
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tags_name ON tags(name);

-- Monitor/tag join. The `join_id` IDENTITY mirrors the D1 `mt.rowid AS
-- join_id`, which the UI uses as the React key for a chip.
--
-- 监控项与标签关联：join_id IDENTITY 对应 D1 的 mt.rowid AS join_id，
-- 界面将其用作徽章的 React key。
CREATE TABLE IF NOT EXISTS monitor_tags (
  monitor_id TEXT NOT NULL,
  tag_id     TEXT NOT NULL,
  join_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (monitor_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_monitor_tags_tag ON monitor_tags(tag_id);

-- Notification-group scope join.
-- 通知与分组范围的关联。
CREATE TABLE IF NOT EXISTS notification_groups (
  notification_id TEXT NOT NULL,
  group_id        TEXT NOT NULL,
  PRIMARY KEY (notification_id, group_id)
);

CREATE INDEX IF NOT EXISTS idx_notification_groups_group ON notification_groups(group_id);

-- ---------------------------------------------------------------------------
-- Agent monitors' live snapshot and per-minute rollup.
-- Agent 监控项的实时快照和每分钟汇总。
CREATE TABLE IF NOT EXISTS machine_live (
  monitor_id          TEXT PRIMARY KEY,
  os                  TEXT,
  arch                TEXT,
  kernel              TEXT,
  cpu_model           TEXT,
  cpu_cores           INTEGER,
  cpu_usage           DOUBLE PRECISION,
  mem_used            BIGINT,
  mem_total           BIGINT,
  swap_used           BIGINT,
  swap_total          BIGINT,
  load_1              DOUBLE PRECISION,
  load_5              DOUBLE PRECISION,
  load_15             DOUBLE PRECISION,
  disk_used           BIGINT,
  disk_total          BIGINT,
  net_up_rate         DOUBLE PRECISION,
  net_down_rate       DOUBLE PRECISION,
  net_up_total        BIGINT,
  net_down_total      BIGINT,
  connections_tcp     INTEGER,
  connections_udp     INTEGER,
  process_count       INTEGER,
  uptime              BIGINT,
  message             TEXT,
  public_ip           TEXT,
  isp                 TEXT,
  region              TEXT,
  virtualization      TEXT,
  transport           TEXT,
  version             TEXT,
  public_ipv6         TEXT,
  report_interval_secs INTEGER,
  interfaces_json     TEXT,
  mounts_json         TEXT,
  reported_at         INTEGER,
  updated_at          INTEGER NOT NULL
);

-- For already-deployed PG databases the CREATE above is a no-op
-- (`IF NOT EXISTS`), so the four agent extras columns also get defensive
-- ALTERs. PG supports `ADD COLUMN IF NOT EXISTS`; SQLite does not, which is
-- why the SQLite chain needs 0014 and this file needs both shapes.
--
-- 已部署 PG 数据库中，上方 CREATE IF NOT EXISTS 是无操作，因此四个 Agent
-- 额外字段还需防御性 ALTER。PG 支持 ADD COLUMN IF NOT EXISTS，SQLite 不支持，
-- 所以 SQLite 迁移链需要 0014，而此文件需要同时覆盖两种状态。
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS public_ip      TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS isp            TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS region         TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS virtualization TEXT;

-- Phase 6: per-NIC and per-mount JSON snapshots, sent on `report`. Same
-- NULLable story as the extras above: old agents never wrote these, the
-- detail page renders NULL as "—".
--
-- 阶段 6：每个网卡和挂载点的 JSON 快照通过 report 发送。与上述额外字段一样
-- 可以为 NULL：旧 Agent 未写入这些字段，详情页将 NULL 显示为“—”。
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS interfaces_json TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS mounts_json     TEXT;

-- The transport an agent is on: 'ws' or 'http'. Reported by the agent in
-- `basicReport` because the server cannot tell a socket from a POST once the
-- frame is parsed. NULL for agents built before the HTTP fallback existed.
--
-- Agent 使用的传输方式为 ws 或 http，由 basicReport 上报，因为帧解析后服务器
-- 无法区分来源是 socket 还是 POST；HTTP 回退出现前构建的 Agent 此字段为 NULL。
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS transport       TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS version         TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS public_ipv6     TEXT;
ALTER TABLE machine_live ADD COLUMN IF NOT EXISTS report_interval_secs INTEGER;

CREATE TABLE IF NOT EXISTS machine_history (
  monitor_id      TEXT    NOT NULL,
  bucket_ts       INTEGER NOT NULL,
  cpu_avg         DOUBLE PRECISION,
  cpu_max         DOUBLE PRECISION,
  mem_pct_avg     DOUBLE PRECISION,
  mem_pct_max     DOUBLE PRECISION,
  load_1_avg      DOUBLE PRECISION,
  load_5_avg      DOUBLE PRECISION,
  sample_count    INTEGER,
  duration_sec    INTEGER,
  quality         TEXT,
  net_up_bytes    BIGINT,
  net_down_bytes  BIGINT,
  network_duration_sec INTEGER,
  PRIMARY KEY (monitor_id, bucket_ts)
);

CREATE TABLE IF NOT EXISTS agent_uptime_daily (
  monitor_id TEXT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  total INTEGER NOT NULL,
  up INTEGER NOT NULL,
  warn INTEGER NOT NULL,
  last_minute_ts INTEGER NOT NULL,
  PRIMARY KEY (monitor_id, day)
);

-- ---------------------------------------------------------------------------
-- Migration ledger. Single-row-per-file bookkeeping the migration runner
-- consults to decide which files have been applied. `name` is the basename
-- (e.g. `0001_init.postgres.sql`); `applied_at` is seconds-since-epoch,
-- consistent with every other timestamp in this schema.
--
-- 迁移账本每个文件一行，供迁移执行器判断已应用文件。name 为文件基本名
--（如 0001_init.postgres.sql），applied_at 为 Unix 秒数，与本模式其他时间戳一致。
CREATE TABLE IF NOT EXISTS schema_migrations (
  name       TEXT PRIMARY KEY,
  applied_at INTEGER NOT NULL
);
