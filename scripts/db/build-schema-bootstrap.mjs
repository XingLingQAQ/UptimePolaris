/**
 * Embed the D1 migration files into the Worker bundle.
 *
 * The Worker cannot read `database/schema/d1/` at runtime (wrangler bundles
 * `src/` only, and Workers have no filesystem), so a fresh deployment would
 * otherwise need `db:init` before the first page loads. Migration files remain
 * the single source of truth; this only changes their shape.
 * 迁移文件仍是唯一来源；这里只把 SQL 变成打包模块。
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const GENERATED = resolve(root, 'backends/worker/src/lib/db/schema-bootstrap.ts');
const GENERATED_POSTGRES = resolve(root, 'backends/worker/src/lib/db/postgres-schema.ts');

export function postgresMigrationPlan(directory = resolve(root, 'database/schema/postgres')) {
  return readdirSync(directory)
    .filter((name) => name.endsWith('.postgres.sql'))
    .sort()
    .map((name) => ({ name, sql: readFileSync(resolve(directory, name), 'utf8') }));
}

export function renderPostgres(plan) {
  return `// Generated by scripts/db/build-schema-bootstrap.mjs. / 由脚本自动生成。\nexport const POSTGRES_MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(plan, null, 2)};\n`;
}

/**
 * The ledger, matching what `wrangler d1 migrations apply` creates.
 *
 * Deliberately the same table and column names: `scripts/db/db-init.mjs` records
 * its baseline there and `wrangler d1 migrations apply` reads it, so a database
 * bootstrapped by the Worker and one migrated by the operator must agree on the
 * same ledger or the two would re-apply each other's files.
 * 迁移记录表与 wrangler d1 migrations apply 使用相同名称和列：db-init.mjs 在此记录基线，
 * Wrangler 读取同一记录，避免 Worker 初始化与操作员迁移互相重复应用文件。
 */
export const LEDGER_DDL =
  'CREATE TABLE IF NOT EXISTS d1_migrations (' +
  'id INTEGER PRIMARY KEY AUTOINCREMENT, ' +
  'name TEXT UNIQUE, ' +
  'applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)';

/**
 * Split one migration file into statements.
 *
 * The same split every test in this repo already performs: drop whole-line `--`
 * comments, then divide on `;`. It is sufficient here and verified as such -
 * no migration has a trailing comment after code, a block comment, a `;` inside
 * a string literal, or a string literal spanning lines. Statements keep their
 * newlines; `prepare()` binds a multi-line statement fine, and collapsing
 * whitespace would be one more way to corrupt a literal.
 * 与本仓库测试使用相同的拆分方式：移除整行 -- 注释，再按分号拆分。
 * 当前迁移不含代码后的行尾注释、块注释、字符串内分号或跨行字符串；现有测试验证了这一前提。
 * 保留语句中的换行，因为 prepare() 可处理多行语句，而折叠空白可能破坏字面量。
 */
export function statementsOf(source) {
  return source
    .split('\n')
    .filter((line) => !line.trim().startsWith('--'))
    .join('\n')
    .split(';')
    .map((statement) => statement.trim())
    .filter(Boolean);
}

export function migrationPlan(directory = resolve(root, 'database/schema/d1')) {
  return readdirSync(directory)
    .filter((name) => name.endsWith('.sql'))
    .sort()
    .map((name) => ({
      name,
      statements: statementsOf(readFileSync(resolve(directory, name), 'utf8')),
    }));
}

export function render(plan) {
  const files = plan
    .map(({ name, statements }) => {
      const list = statements.map((statement) => `      ${JSON.stringify(statement)},`).join('\n');
      return `  {\n    name: ${JSON.stringify(name)},\n    statements: [\n${list}\n    ],\n  },`;
    })
    .join('\n');

  return `/**
 * GENERATED FILE - do not edit by hand.
 *
 * The D1 schema, as statements, embedded for \`backends/worker/src/lib/db/bootstrap.ts\` to apply
 * on the first request against an empty database. Written by
 * \`scripts/db/build-schema-bootstrap.mjs\` from \`database/schema/d1/*.sql\`, which remain
 * the source of truth; \`test/db/schema-bootstrap.test.mjs\` fails if this copy and
 * those files disagree.
 *
 * Regenerate with \`npm run schema:build\`.
 *
 * 自动生成的 D1 迁移语句，供 backends/worker/src/lib/db/bootstrap.ts 在空库首次请求时执行。
 * scripts/db/build-schema-bootstrap.mjs 从作为真实来源的 database/schema/d1/*.sql 生成本文件；
 * test/db/schema-bootstrap.test.mjs 会检查两者是否一致。使用 npm run schema:build 重新生成。
 */

export interface BootstrapFile {
  /** The migration's filename, as the ledger records it. / 迁移记录表中的文件名。 */
  name: string;
  statements: readonly string[];
}

/**
 * The migration ledger, matching the one \`wrangler d1 migrations apply\` writes.
 *
 * Same table and columns on purpose: an operator who runs \`npm run db:init\`
 * afterwards must find this ledger already correct rather than a second,
 * parallel record of what has been applied.
 * 迁移记录表与 wrangler d1 migrations apply 的表及列一致；操作员后续运行 npm run db:init
 * 时会找到正确的现有记录，而非另一份并行记录。
 */
export const LEDGER_DDL = ${JSON.stringify(LEDGER_DDL)};

/** Every D1 migration, in application order. / 按执行顺序排列的全部 D1 迁移。 */
export const BOOTSTRAP_FILES: readonly BootstrapFile[] = [
${files}
];
`;
}

/*
  Only when run as a script.

  `test/db/schema-bootstrap.test.mjs` imports `migrationPlan` and `render` to compare
  what the generator *would* write against what is committed. Without this guard
  the import would also execute the branch below and overwrite the very file the
  test is checking - which would make the staleness assertion unfalsifiable, and
  let a test run silently repair the drift it exists to catch.

  仅直接运行脚本时生成文件。test/db/schema-bootstrap.test.mjs 导入 migrationPlan 和 render，
  比较生成结果与提交的文件；没有此保护时导入会覆盖被测文件，使过期断言无法失败，
  测试也会悄悄修复它本应发现的偏差。
*/
const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);

if (invokedDirectly) {
  const plan = migrationPlan();
  const output = render(plan);
  const postgresPlan = postgresMigrationPlan();
  const postgresOutput = renderPostgres(postgresPlan);

  if (process.argv.includes('--check')) {
    const current = readFileSync(GENERATED, 'utf8');
    const postgresCurrent = readFileSync(GENERATED_POSTGRES, 'utf8');
    if (current !== output || postgresCurrent !== postgresOutput) {
      console.error('[schema:build] embedded database schema is stale; run `npm run schema:build`');
      process.exitCode = 1;
    } else {
      console.log(`[schema:build] up to date (${plan.length} migrations)`);
    }
  } else {
    writeFileSync(GENERATED, output, 'utf8');
    writeFileSync(GENERATED_POSTGRES, postgresOutput, 'utf8');
    const statements = plan.reduce((total, file) => total + file.statements.length, 0);
    console.log(`[schema:build] wrote ${plan.length} migrations / ${statements} statements`);
  }
}
