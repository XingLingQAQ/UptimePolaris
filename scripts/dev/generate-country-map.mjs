import { readFile, writeFile } from 'node:fs/promises';

// Natural Earth 1:50m admin-0, public domain: https://www.naturalearthdata.com/about/terms-of-use/
// Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
const [input, output = 'frontend/src/components/servers/world-countries.ts'] = process.argv.slice(2);
if (!input) throw new Error('Usage: node scripts/dev/generate-country-map.mjs <countries.geojson> [output.ts]');
const source = JSON.parse(await readFile(input, 'utf8'));

function simplify(points, tolerance = 0.12) {
  if (points.length < 5) return points;
  const keep = new Set([0, points.length - 1]);
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [start, end] = stack.pop();
    const [ax, ay] = points[start], [bx, by] = points[end];
    const dx = bx - ax, dy = by - ay, length = dx * dx + dy * dy;
    let furthest = -1, distance = tolerance * tolerance;
    for (let index = start + 1; index < end; index++) {
      const [x, y] = points[index];
      const t = length ? Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / length)) : 0;
      const squared = (x - ax - t * dx) ** 2 + (y - ay - t * dy) ** 2;
      if (squared > distance) { distance = squared; furthest = index; }
    }
    if (furthest < 0) continue;
    keep.add(furthest);
    stack.push([start, furthest], [furthest, end]);
  }
  const result = [...keep].sort((a, b) => a - b).map(index => points[index]);
  return result.length >= 4 ? result : points;
}

const coordinate = ([lon, lat]) => [((lon + 180) * 1000 / 360).toFixed(2), ((84 - lat) * 1000 / 360).toFixed(2)].join(',');
const paths = {};
for (const feature of source.features) {
  const code = feature.properties.ISO_A2_EH;
  if (code === 'AQ') continue;
  const key = /^[A-Z]{2}$/.test(code) ? code : feature.properties.ADM0_A3;
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const path = polygons.flatMap(polygon => polygon.map(ring => `M${simplify(ring).map(coordinate).join('L')}Z`)).join('');
  paths[key] = (paths[key] ?? '') + path;
}
await writeFile(output, `// Natural Earth 1:50m admin-0, public domain. Generated by scripts/dev/generate-country-map.mjs.\n// https://www.naturalearthdata.com/about/terms-of-use/\nexport const COUNTRY_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)};\n`);
console.log(`Generated ${Object.keys(paths).length} country/region paths in ${output}`);
